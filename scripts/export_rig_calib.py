#!/usr/bin/env python3
"""Write calib/rig_calib.json from the calibration result files, so runtime values never drift from them.

Sources: the wrist-mount fit (fit_joint_offsets.py --mount-output) and the scene solve
(solve_scene_to_base.py). Intrinsics stay in camera_calibration.json, which CalibrationStore
overlays at load time, so they are not copied here. Keys not owned by these sources
(gripper, home pose, ...) are preserved.
"""
import argparse
import json
from pathlib import Path
import subprocess
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from desk_core.calib_store import CAMERA_ONLY_KEYS, resolve_camera_calib_path


def dumps(value, indent=0):
    pad, inner = "  " * indent, "  " * (indent + 1)
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = [f"{inner}{json.dumps(k)}: {dumps(v, indent + 1)}" for k, v in value.items()]
        return "{\n" + ",\n".join(items) + f"\n{pad}}}"
    if isinstance(value, list) and value and not all(isinstance(v, (int, float)) for v in value):
        return "[\n" + ",\n".join(f"{inner}{dumps(v, indent + 1)}" for v in value) + f"\n{pad}]"
    return json.dumps(value, ensure_ascii=False)


def git_commit():
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                              capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--calibration", type=Path, default=ROOT / "calib_frames/session1/camera_calibration.json")
    parser.add_argument("--wrist-mount", type=Path, default=ROOT / "calib_frames/hand_eye_combined/wrist_mount_final.json")
    parser.add_argument("--scene", type=Path, default=ROOT / "calib_frames/scene_1/scene_to_base.json")
    parser.add_argument("--scene-capture", type=Path, default=ROOT / "calib_frames/scene_1/capture.json")
    parser.add_argument("--rig", type=Path, default=ROOT / "calib/rig_calib.json")
    args = parser.parse_args()

    mount = json.loads(args.wrist_mount.read_text())
    scene = json.loads(args.scene.read_text())
    capture = json.loads(args.scene_capture.read_text())
    rig = json.loads(args.rig.read_text())

    base_board = np.asarray(mount["T_base_board"])
    board_normal = base_board[:3, 2]
    if abs(board_normal[2]) < 0.99:
        raise SystemExit(f"Board is tilted {np.degrees(np.arccos(abs(board_normal[2]))):.1f} deg from the base XY plane; "
                         "z_table from the board would be unreliable.")

    rig["calibrated"] = True
    rig["hardware"] = {"bus_serial": capture["bus"], "camera_top": capture["scene_camera"],
                       "camera_wrist": capture["wrist_camera"]}
    rig["joint_zero_ticks"] = mount["joint_zero_ticks"]
    rig["joint_signs"] = mount["joint_signs"]
    rig["z_table"] = round(float(base_board[2, 3]), 5)
    loaded = resolve_camera_calib_path()
    if loaded is None or loaded.resolve() != args.calibration.resolve():
        raise SystemExit(f"CalibrationStore would load intrinsics from {loaded}, but the transforms were "
                         f"solved with {args.calibration}; make that the newest camera_calibration.json.")
    for key in CAMERA_ONLY_KEYS:
        rig.pop(key, None)
    rig["T_world_cam_top"] = scene["T_base_cam_scene"]
    rig["T_ee_cam_wrist"] = mount["T_ee_cam_wrist"]
    # A placeholder H_table would override T_world_cam_top in CalibrationStore.pixel_to_world.
    rig.pop("H_table", None)

    notes = rig.setdefault("_notes", {})
    notes["status_hint"] = "Generated by scripts/export_rig_calib.py; rerun it instead of editing calibrated values by hand."
    notes["sources"] = {
        "intrinsics (overlaid by CalibrationStore, not copied)": str(args.calibration.relative_to(ROOT)),
        "T_ee_cam_wrist, joint_zero_ticks, joint_signs, z_table": str(args.wrist_mount.relative_to(ROOT)),
        "T_world_cam_top": str(args.scene.relative_to(ROOT)),
        "hardware": str(args.scene_capture.relative_to(ROOT)),
        "exported_at_commit": git_commit(),
    }
    notes["accuracy"] = {
        "wrist_fit_board_consistency_mm_deg": [round(mount["fit_consistency"]["board_origin_pairwise_rms_mm"], 1),
                                               round(mount["fit_consistency"]["board_rotation_pairwise_rms_deg"], 2)],
        "scene_board_moved_check_mm_deg": [scene["board_moved_check"]["wrist_view_vs_T_base_board_mm"],
                                           scene["board_moved_check"]["wrist_view_vs_T_base_board_deg"]],
    }
    notes["valid_while"] = ("Station motor ranges (station_data) and servo offsets are unchanged, the wrist camera "
                            "mount is untouched, the scene camera is not moved, and streams run at the intrinsics' "
                            "image size (1280x720).")

    args.rig.write_text(dumps(rig) + "\n")
    print(f"Wrote {args.rig}")


if __name__ == "__main__":
    main()
